function hintKey(name) {
  return String(name || '').toLowerCase().replace(/ё/g, 'е').replace(/\s*\[[^\]]*\]\s*/g, ' ').replace(/[«»"'’`.,:;()]/g, ' ').replace(/\s+/g, ' ').trim();
}

function buildHintIndex(list) {
  const map = new Map();
  for (const h of list) for (const n of h.names) map.set(hintKey(n), h);
  return map;
}

const SPELL_HINT_INDEX = buildHintIndex(SPELL_HINTS);
const FEATURE_HINT_INDEX = buildHintIndex(FEATURE_HINTS);

// Подсказка для заклинания или умения: сначала своя (вписанная игроком), потом встроенная
function findHint(kind, obj) {
  if (obj && obj.hint && String(obj.hint).trim()) return { own: true, text: String(obj.hint).trim() };
  const index = kind === 'spell' ? SPELL_HINT_INDEX : FEATURE_HINT_INDEX;
  const keys = [hintKey(obj && obj.name)];
  if (obj && obj.en) keys.push(hintKey(obj.en));
  for (const k of keys) {
    const h = index.get(k);
    if (h) return { own: false, meta: h.meta || '', what: h.what, when: h.when };
  }
  return null;
}
